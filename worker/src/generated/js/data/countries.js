// Intl.DisplayNames wrapper, cached per language.
const dnCache = {};
export function countryName(a2, lang) {
  const loc = lang === 'zh' ? 'zh-CN' : 'en';
  try {
    dnCache[loc] ||= new Intl.DisplayNames([loc], { type: 'region' });
    return dnCache[loc].of(a2) || a2;
  } catch {
    return a2;
  }
}
